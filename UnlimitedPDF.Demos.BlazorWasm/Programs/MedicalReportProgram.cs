// Medical report: a laboratory report with patient details, results, reference ranges, and flags.
// A complete console program: it writes medical-report.pdf.
//
// Run it:
//   1. dotnet new console -n MedicalReportExample
//   2. cd MedicalReportExample
//   3. dotnet add package UnlimitedPDF
//   4. Replace everything in Program.cs with this code.
//   5. Save these images in the MedicalReportExample folder, next to Program.cs:
//        https://unlimitedpdf.dev/images/medical-report-logo.png
//   6. dotnet run
// Then open medical-report.pdf in the MedicalReportExample folder.

using UnlimitedPDF;

namespace MedicalReportExample;

public static class Program
{
    private const double Left = 50;

    // Light tints of the logo's blue and green: text stays black, so fills carry the color.
    private static readonly PdfColor BandTint = new(0.91, 0.96, 0.94);
    private static readonly PdfColor Flagged = new(1.0, 0.9, 0.9);
    private static readonly PdfColor Green = new(0.13, 0.60, 0.25);
    private static readonly PdfColor HeaderTint = new(0.82, 0.89, 0.97);
    private static readonly PdfColor LabelShade = new(0.94, 0.96, 0.99);
    private static readonly PdfColor SectionTint = new(0.89, 0.94, 0.99);

    public static void Main()
    {
        // The sample data: change it, run again, and open medical-report.pdf.
        // Every name and value is fictional.
        string patientName = "Alex Sample";
        string patientId = "PID-000123";
        int age = 34;
        string sex = "Female";
        string referredBy = "Dr. Jamie Example";
        DateTime collectedOn = DateTime.Today;
        DateTime reportedOn = DateTime.Today;
        LabResult[] labResults =
        [
            new("Hemoglobin", "13.5", "g/dL", 12.0, 15.5),
            new("White blood cells", "11.8", "x10^3/uL", 4.0, 11.0),
            new("Red blood cells", "4.6", "x10^6/uL", 4.2, 5.4),
            new("Platelets", "250", "x10^3/uL", 150, 400),
            new("Fasting glucose", "108", "mg/dL", 70, 99),
        ];

        // The side margins stay 0 so the header band runs edge to edge; content is placed 50 pt in.
        var document = new PdfDocument { MarginBottom = 24 };
        var (pageWidth, _) = PdfPageSize.A4.ToDimensions();

        // The lab header and the footer note are drawn on every page.
        document.Header.Height = 94;
        document.Header.AddRectangle(0, 0, pageWidth, 90, BandTint);
        document.Header.AddRectangle(0, 90, pageWidth, 4, Green);
        var logo = PdfImage.FromFile("medical-report-logo.png");
        var contain = new PdfImagePlacementOptions { Fit = PdfImageFit.Contain };
        document.Header.AddImage(logo, Left, 22, 130, 45, contain);
        document.Header.AddText("UnlimitedPDF Reports", 370, 24, 14);
        document.Header.AddText("12 Sample Street, Demo City 000000", 370, 43, 9);
        document.Header.AddText("Phone: 000-000-0000", 370, 55, 9);

        document.Footer.Height = 28;
        document.Footer.AddRectangle(Left, 0, 495, 2, Green);
        document.Footer.AddText(
            "Sample report with fictional data, generated by UnlimitedPDF.", Left, 10, 8);
        document.Footer.AddText("Page {page} of {pages}", Left, 10, 8, PdfTextAlignment.Right);

        document.BodyMarginTop = 20;
        document.BodyMarginBottom = 16;
        var body = document.Body;

        body.AddText("LABORATORY REPORT", fontSize: 16, alignment: PdfTextAlignment.Center);

        // Patient details: label and value pairs in a four-column table.
        var patient = body.AddTable(495, spacing: 10, x: Left);
        patient.SetColumnWidths(90, 160, 90, 155);
        string[,] details =
        {
            { "Patient name", patientName, "Patient ID", patientId },
            { "Age / Sex", $"{age} / {sex}", "Referred by", referredBy },
            {
                "Collected", collectedOn.ToString("dd-MMM-yyyy"),
                "Reported", reportedOn.ToString("dd-MMM-yyyy")
            },
        };

        for (int row = 0; row < details.GetLength(0); row++)
        {
            for (int column = 0; column < 4; column++)
            {
                var cell = patient.GetOrCreateCell(row, column);
                cell.Text = details[row, column];
                if (column % 2 == 0)
                {
                    cell.BackgroundColor = LabelShade;
                }
            }
        }

        // The section title and its rule stay on the page of the first results row.
        body.AddText("Test results", spacing: 18, fontSize: 12, x: Left, keepWithNext: true);
        body.AddRectangle(495, 2, SectionTint, spacing: 3, x: Left, keepWithNext: true);

        // Long results continue on new pages with their header row repeated.
        var results = body.AddTable(495, spacing: 6, x: Left);
        results.SetColumnWidths(165, 70, 80, 120, 60);
        results.HeaderRowCount = 1;
        results.RepeatHeaderRows = true;
        var header = results.AddRow();
        string[] headings = ["Test", "Result", "Unit", "Reference range", "Flag"];
        for (int column = 0; column < headings.Length; column++)
        {
            header.GetCell(column).Text = headings[column];
            header.GetCell(column).BackgroundColor = HeaderTint;
        }

        foreach (var result in labResults)
        {
            string flag = Flag(result);
            var row = results.AddRow();
            row.GetCell(0).Text = result.Test;
            row.GetCell(1).Text = result.Result;
            row.GetCell(1).HorizontalAlignment = PdfCellHorizontalAlignment.Right;
            row.GetCell(2).Text = result.Unit;
            row.GetCell(3).Text = $"{result.Low:0.##} - {result.High:0.##}";
            row.GetCell(4).Text = flag;
            row.GetCell(4).HorizontalAlignment = PdfCellHorizontalAlignment.Center;

            if (flag.Length > 0)
            {
                for (int column = 0; column < 5; column++)
                {
                    row.GetCell(column).BackgroundColor = Flagged;
                }
            }
        }

        // The notes follow the last result and stay together.
        var notes = body.AddBlock(spacing: 14);
        notes.AddText("H = above the reference range, L = below it.", fontSize: 9, x: Left);
        notes.AddText(
            "Results should be interpreted by a qualified clinician.",
            spacing: 2, fontSize: 9, x: Left);

        document.Save("medical-report.pdf");
        Console.WriteLine($"Wrote {Path.GetFullPath("medical-report.pdf")}");
    }

    // "H" above the range, "L" below it, empty inside it or when the result is not a number.
    private static string Flag(LabResult result)
    {
        if (!double.TryParse(
            result.Result,
            System.Globalization.NumberStyles.Float,
            System.Globalization.CultureInfo.InvariantCulture,
            out var value))
        {
            return "";
        }

        return value > result.High ? "H" : value < result.Low ? "L" : "";
    }

    // One test: the result as written, its unit, and the reference range.
    private sealed record LabResult(
        string Test, string Result, string Unit, double Low, double High);
}
