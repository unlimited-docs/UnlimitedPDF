using System.Globalization;
using UnlimitedPDF.Demos.BlazorWasm.Samples.Inputs;
using UnlimitedPDF.Enums;
using UnlimitedPDF.Extensions;
using UnlimitedPDF.Models.Table;

namespace UnlimitedPDF.Demos.BlazorWasm.Samples;

/// <summary>
/// Medical report: a lab header and a footer note on every page, patient details, and results with reference ranges and
/// High or Low flags. Long results continue on new pages with their header row repeated.
/// </summary>
public static class MedicalReportSample
{
    #region Fields and Constants

    private const double Left = 50;

    // Light tints of the logo's blue and green: text stays black, so fills carry the color.
    private static readonly PdfColor _bandTint = new(0.91, 0.96, 0.94);
    private static readonly PdfColor _flagged = new(1.0, 0.9, 0.9);
    private static readonly PdfColor _green = new(0.13, 0.60, 0.25);
    private static readonly PdfColor _headerTint = new(0.82, 0.89, 0.97);
    private static readonly PdfColor _labelShade = new(0.94, 0.96, 0.99);
    private static readonly PdfColor _sectionTint = new(0.89, 0.94, 0.99);

    #endregion

    #region Methods

    #region Public Methods

    /// <summary>
    /// Builds the document.
    /// </summary>
    /// <param name="input">The report data (fictional).</param>
    /// <param name="images">The lab logo ("medical-report-logo.png").</param>
    /// <returns>The document, ready to save.</returns>
    public static PdfDocument Build(MedicalReportInput input, SampleImages images)
    {
        // The side margins stay 0 so the header band runs edge to edge; content is placed 50 pt in.
        var document = new PdfDocument { BottomMargin = 24 };
        var (pageWidth, _) = PdfPageSize.A4.ToDimensions();

        // The lab header and the footer note are drawn on every page.
        document.Header.Height = 94;
        document.Header.AddRectangle(0, 0, pageWidth, 90, _bandTint);
        document.Header.AddRectangle(0, 90, pageWidth, 4, _green);
        document.Header.AddImage(images["medical-report-logo.png"], Left, 22, 130, 45, new PdfImagePlacementOptions { Fit = PdfImageFit.Contain });
        document.Header.AddText("UnlimitedPDF Reports", 370, 24, 14);
        document.Header.AddText("12 Sample Street, Demo City 000000", 370, 43, 9);
        document.Header.AddText("Phone: 000-000-0000", 370, 55, 9);

        document.Footer.Height = 28;
        document.Footer.AddRectangle(Left, 0, 495, 2, _green);
        document.Footer.AddText("Sample report with fictional data, generated by UnlimitedPDF.", Left, 10, 8);
        document.Footer.AddText("Page {page} of {pages}", Left, 10, 8, PdfTextAlignment.Right);

        document.Body.TopGap = 20;
        document.Body.BottomGap = 16;
        var body = document.Body;

        body.AddText("LABORATORY REPORT", fontSize: 16, alignment: PdfTextAlignment.Center);

        // Patient details: label and value pairs in a four-column table.
        var patient = body.AddTable(495, spacing: 10, x: Left);
        patient.SetColumnWidths(90, 160, 90, 155);
        string[,] details =
        {
            { "Patient name", input.PatientName, "Patient ID", input.PatientId },
            { "Age / Sex", $"{input.Age} / {input.Sex}", "Referred by", input.ReferredBy },
            { "Collected", input.CollectedOn.ToString("dd-MMM-yyyy"), "Reported", input.ReportedOn.ToString("dd-MMM-yyyy") }
        };

        for (int row = 0; row < details.GetLength(0); row++)
        {
            for (int column = 0; column < 4; column++)
            {
                var cell = patient.GetOrCreateCell(row, column);
                cell.Text = details[row, column];
                if (column % 2 == 0)
                {
                    cell.Background = _labelShade;
                }
            }
        }

        // The section title and its rule stay on the page of the first results row.
        body.AddText("Test results", spacing: 18, fontSize: 12, x: Left, keepWithNext: true);
        body.AddRectangle(495, 2, _sectionTint, spacing: 3, x: Left, keepWithNext: true);

        var results = body.AddTable(495, spacing: 6, x: Left);
        results.SetColumnWidths(165, 70, 80, 120, 60);
        results.HeaderRowCount = 1;
        results.RepeatHeaderRows = true;
        var header = results.AddRow();
        string[] headings = ["Test", "Result", "Unit", "Reference range", "Flag"];
        for (int column = 0; column < headings.Length; column++)
        {
            header.GetCell(column).Text = headings[column];
            header.GetCell(column).Background = _headerTint;
        }

        foreach (var result in input.Results)
        {
            string flag = Flag(result);
            var row = results.AddRow();
            row.GetCell(0).Text = result.Test;
            row.GetCell(1).Text = result.Result;
            row.GetCell(1).HAlign = PdfCellHorizontalAlignment.Right;
            row.GetCell(2).Text = result.Unit;
            row.GetCell(3).Text = $"{result.Low:0.##} - {result.High:0.##}";
            row.GetCell(4).Text = flag;
            row.GetCell(4).HAlign = PdfCellHorizontalAlignment.Center;

            if (flag.Length > 0)
            {
                for (int column = 0; column < 5; column++)
                {
                    row.GetCell(column).Background = _flagged;
                }
            }
        }

        // The notes follow the last result and stay together.
        var notes = body.AddBlock(spacing: 14);
        notes.AddText("H = above the reference range, L = below it.", fontSize: 9, x: Left);
        notes.AddText("Results should be interpreted by a qualified clinician.", spacing: 2, fontSize: 9, x: Left);

        return document;
    }

    #endregion

    #region Private Methods

    // "H" above the range, "L" below it, empty inside it or when the result is not a number.
    private static string Flag(LabResult result)
    {
        if (!double.TryParse(result.Result, NumberStyles.Float, CultureInfo.InvariantCulture, out var value))
        {
            return "";
        }

        return value > result.High ? "H" : value < result.Low ? "L" : "";
    }

    #endregion

    #endregion
}
